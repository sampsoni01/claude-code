#!/usr/bin/env node
/* Animazing — single-file builder.
   Inlines the stylesheet and every script into one self-contained .html that
   runs from a file:// double-click, an email attachment, or any static host
   with no server, no bundler and no network access.

   Usage:
     node tools/build-single.js [outfile]              (default: dist/animazing.html)
     node tools/build-single.js --fragment out.html    (no <html>/<head>/<body>
                                                        wrapper — for embedding
                                                        hosts that supply one)
     node tools/build-single.js --title "Animazing"    (override the page title)

   Script order is read from index.html, so adding a content pack there
   automatically includes it in the build. */
'use strict';

var fs = require('fs');
var path = require('path');

var ROOT = path.join(__dirname, '..');
var args = process.argv.slice(2);
var fragment = args.indexOf('--fragment') >= 0;

/* Positional args are anything that is neither a flag nor a flag's value. */
var VALUE_FLAGS = ['--title'];
var positional = [];
for (var ai = 0; ai < args.length; ai++) {
  if (args[ai].indexOf('--') === 0) {
    if (VALUE_FLAGS.indexOf(args[ai]) >= 0) ai++; // skip its value
    continue;
  }
  positional.push(args[ai]);
}
var outArg = positional[0];
var OUT = path.resolve(ROOT, outArg || (fragment ? 'dist/animazing-fragment.html' : 'dist/animazing.html'));

var indexHtml = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');

function attrs(tag, name) {
  var m = new RegExp(name + '="([^"]+)"').exec(tag);
  return m ? m[1] : null;
}

/* Collect sources in document order. */
var cssFiles = (indexHtml.match(/<link[^>]+rel="stylesheet"[^>]*>/g) || [])
  .map(function (t) { return attrs(t, 'href'); }).filter(Boolean);
var jsFiles = (indexHtml.match(/<script[^>]+src="[^"]+"[^>]*><\/script>/g) || [])
  .map(function (t) { return attrs(t, 'src'); }).filter(Boolean);

if (!jsFiles.length) { console.error('No scripts found in index.html — aborting.'); process.exit(1); }

/* Body markup, stripped of the tags we are inlining. */
var bodyMatch = /<body[^>]*>([\s\S]*)<\/body>/i.exec(indexHtml);
var body = (bodyMatch ? bodyMatch[1] : indexHtml)
  .replace(/<script[^>]+src="[^"]+"[^>]*><\/script>/g, '')
  .replace(/<!--[\s\S]*?-->/g, '')
  .replace(/\n{3,}/g, '\n\n')
  .trim();

var titleMatch = /<title>([^<]*)<\/title>/i.exec(indexHtml);
var titleFlag = args.indexOf('--title');
var title = titleFlag >= 0 && args[titleFlag + 1] ? args[titleFlag + 1]
  : (titleMatch ? titleMatch[1] : 'Animazing');
var iconMatch = /<link[^>]+rel="icon"[^>]*>/i.exec(indexHtml);
var iconTag = iconMatch ? iconMatch[0] : '';

/* A literal </script> inside a JS string would close the inline block early. */
function safeJs(src) { return src.replace(/<\/script/gi, '<\\/script'); }

function read(rel) {
  var file = path.join(ROOT, rel);
  if (!fs.existsSync(file)) { console.error('Missing source: ' + rel); process.exit(1); }
  return fs.readFileSync(file, 'utf8');
}

var css = cssFiles.map(function (f) {
  return '/* ===== ' + f + ' ===== */\n' + read(f);
}).join('\n\n');

var js = jsFiles.map(function (f) {
  return '/* ===== ' + f + ' ===== */\n' + safeJs(read(f));
}).join('\n\n');

var banner = '<!-- Animazing — single-file build. Generated by tools/build-single.js;\n' +
  '     edit the sources under css/ and js/, not this file. -->';

var parts = [];
if (fragment) {
  /* Host supplies the document shell (e.g. an artifact wrapper). */
  parts.push('<title>' + title + '</title>');
  parts.push(banner);
  parts.push('<style>\n' + css + '\n</style>');
  parts.push(body);
  parts.push('<script>\n' + js + '\n</script>');
} else {
  parts.push('<!DOCTYPE html>');
  parts.push('<html lang="en">');
  parts.push('<head>');
  parts.push('<meta charset="UTF-8">');
  parts.push('<meta name="viewport" content="width=device-width, initial-scale=1.0">');
  parts.push('<title>' + title + '</title>');
  if (iconTag) parts.push(iconTag);
  parts.push(banner);
  parts.push('<style>\n' + css + '\n</style>');
  parts.push('</head>');
  parts.push('<body>');
  parts.push(body);
  parts.push('<script>\n' + js + '\n</script>');
  parts.push('</body>');
  parts.push('</html>');
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, parts.join('\n') + '\n');

var kb = (fs.statSync(OUT).size / 1024).toFixed(0);
console.log('Built ' + path.relative(ROOT, OUT) + '  (' + kb + ' KB, ' +
  cssFiles.length + ' stylesheet(s) + ' + jsFiles.length + ' scripts inlined)');
